#!/usr/bin/env python3
"""Project manually recorded owner-photo routes into clean nominal PCB geometry.
No image textures or photographed wear are carried into the model. Standard library only.
"""
from pathlib import Path
import json,math
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'keyboard-artwork.json').read_text())
def homography(src,dst):
    rows=[]
    for (x,y),(u,v) in zip(src,dst):
        rows.extend([[x,y,1,0,0,0,-u*x,-u*y,u],[0,0,0,x,y,1,-v*x,-v*y,v]])
    for i in range(8):
        pivot=max(range(i,8),key=lambda j:abs(rows[j][i]));rows[i],rows[pivot]=rows[pivot],rows[i]
        scale=rows[i][i];assert abs(scale)>1e-12
        rows[i]=[v/scale for v in rows[i]]
        for j in range(8):
            if j!=i:
                scale=rows[j][i];rows[j]=[a-scale*b for a,b in zip(rows[j],rows[i])]
    return [row[-1] for row in rows]+[1]
def project(h,p):
    x,y=p;d=h[6]*x+h[7]*y+1
    return [round((h[0]*x+h[1]*y+h[2])/d,3),round((h[3]*x+h[4]*y+h[5])/d,3)]
lines=['// Generated by tools/configure-keyboard-artwork.py; owner photos, MIT.','// Visual tracing, not a circuit reconstruction. See keyboard-artwork.json.']
for name in ['matrix','controller','controller_top']:
    a=data[name];h=homography(a['corners'],a['modelCorners'])
    for p,q in zip(a['corners'],a['modelCorners']):assert math.dist(project(h,p),q)<.002
    for field in ['paths','pads']:
        if field not in a:continue
        values=[[project(h,p) for p in path] for path in a[field]] if field=='paths' else [project(h,p) for p in a[field]]
        if name=='controller_top' and field=='paths':
            # Edge tracks retain a nominal 0.5 mm copper-to-edge margin.
            values=[[[max(-134.5,min(134.5,x)),max(-22.5,min(22.5,y))] for x,y in path] for path in values]
        lines.append(name+'_photo_'+field+'='+json.dumps(values,separators=(',',':'))+';')
(root/'keyboard-artwork.scad').write_text('\n'.join(lines)+'\n')
print('Projected',len(data['matrix']['paths']),'matrix and',len(data['controller']['paths']),'controller routes')
